const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('ice', Object.freeze({
  request: (method, params = {}) => ipcRenderer.invoke('ice:request', method, params),
  readRules:()=>ipcRenderer.invoke('ice:read-rules'),
  chooseWorkspace:()=>ipcRenderer.invoke('ice:choose-workspace'),
  copyArticle:jobId=>ipcRenderer.invoke('ice:copy-article',jobId),
  captureWeb:(url,selector)=>ipcRenderer.invoke('ice:capture-web',url,selector),
  captureArticle:jobId=>ipcRenderer.invoke('ice:capture-article',jobId),
  importImage: (jobId, figureNo) => ipcRenderer.invoke('ice:import-image', jobId, figureNo),
  importArticle: accountId => ipcRenderer.invoke('ice:import-article',accountId),
  importOutline: accountId => ipcRenderer.invoke('ice:import-outline',accountId),
  importCreativeDocument: accountId => ipcRenderer.invoke('ice:import-creative-document',accountId),
  pickKnowledgeFile: () => ipcRenderer.invoke('ice:pick-knowledge-file'),
  chooseExportDir: () => ipcRenderer.invoke('ice:choose-export-dir'),
  saveKey: (provider, key) => ipcRenderer.invoke('ice:save-key', provider, key),
  openFolder: jobId => ipcRenderer.invoke('ice:open-folder', jobId),
  openHTML: jobId => ipcRenderer.invoke('ice:open-html', jobId),
  createBackup: () => ipcRenderer.invoke('ice:create-backup'),
  inspectBackup: () => ipcRenderer.invoke('ice:inspect-backup'),
  restoreBackup: token => ipcRenderer.invoke('ice:restore-backup',token),
  openTapNow: () => ipcRenderer.invoke('ice:tapnow'),
  switchUi: mode => ipcRenderer.invoke('ice:switch-ui', mode),
  relaunch: () => ipcRenderer.invoke('ice:relaunch'),
  browserShow: params => ipcRenderer.invoke('ice:browser-show',params),
  browserHide: () => ipcRenderer.invoke('ice:browser-hide'),
  browserBounds: bounds => ipcRenderer.invoke('ice:browser-bounds',bounds),
  browserCommand: (action,value) => ipcRenderer.invoke('ice:browser-command',action,value),
  onBrowserState: callback => {const listener=(_event,state)=>callback(state);ipcRenderer.on('ice:browser-state',listener);return ()=>ipcRenderer.removeListener('ice:browser-state',listener);},
  onBrowserRoute: callback => {const listener=(_event,state)=>callback(state.site);ipcRenderer.on('ice:browser-route',listener);return ()=>ipcRenderer.removeListener('ice:browser-route',listener);},
  onCommandPalette: callback => {const listener=()=>callback();ipcRenderer.on('ice:command-palette',listener);return ()=>ipcRenderer.removeListener('ice:command-palette',listener);},
  captureWindow: () => ipcRenderer.invoke('ice:capture-window'),
  captureRun: (jobId,figureNo,runKeys) => ipcRenderer.invoke('ice:capture-run',jobId,figureNo,runKeys),
  copyText: text => ipcRenderer.invoke('ice:copy-text',text),
  importPublication: () => ipcRenderer.invoke('ice:import-publication'),
  exportPublication: () => ipcRenderer.invoke('ice:export-publication'),
  importResource: () => ipcRenderer.invoke('ice:import-resource'),
  importDraft: () => ipcRenderer.invoke('ice:import-draft'),
  exportDraft: draftId => ipcRenderer.invoke('ice:export-draft', draftId),
  onEngineExit: callback => { const listener = () => callback(); ipcRenderer.on('ice:engine-exit', listener); return () => ipcRenderer.removeListener('ice:engine-exit', listener); }
}));
